/**
 * `GasSwapper` — typed wrapper around the parent-chain GasSwapper
 * helper contract.
 *
 * The contract isn't deployed on every network; consumers that don't
 * need the swap-and-bridge entry point can simply not instantiate
 * this.
 */

import type { Hex, Adapter, PreparedTx, TxResult } from '../adapter.js';
import type { ContractCallerOptions } from '../internal/contract-caller.js';
import type { Logger } from '../logger.js';

import { GasSwapperABI } from '../abi/GasSwapper.js';
import { DepositError, InvalidHexStringError, withOperation } from '../errors.js';
import { ContractCaller } from '../internal/contract-caller.js';
import { BufferUtil } from '../utils/buffer-utils.js';
import { bytesToHex } from '../utils/bytes.js';

export interface GasSwapperConfig {
  adapter: Adapter;
  getAddress: () => Promise<Hex>;
  logger: Logger;
  defaultFrom?: Hex;
  /** Pinned id of the chain this contract is on; see `ContractCallerConfig.chainId`. */
  chainId?: number;
}

/**
 * The number a hex `depositAmount` stands for. The contract takes a `uint256`
 * and the adapter takes an integer, so the hex the callers build
 * (`encodeParameters([amount], ['uint256'])`) is read here, once, instead of
 * being left for each web3 library to read in its own way. A value that is
 * not `0x`-prefixed hex, or has no digits, is rejected as the SDK's own
 * malformed-hex error rather than a bare `SyntaxError` from `BigInt`.
 */
function amountOf(depositAmount: string): bigint {
  const bytes = BufferUtil.toBuffer(depositAmount);
  if (bytes.length === 0) {
    throw new InvalidHexStringError('depositAmount must be 0x-prefixed hex with at least one digit', {
      info: { value: depositAmount }
    });
  }
  return BigInt(`0x${bytesToHex(bytes)}`);
}

export class GasSwapper {
  readonly #caller: ContractCaller<typeof GasSwapperABI>;

  constructor(config: GasSwapperConfig) {
    this.#caller = new ContractCaller({
      adapter: config.adapter,
      getAddress: config.getAddress,
      abi: GasSwapperABI,
      isParent: true,
      logger: config.logger,
      defaultFrom: config.defaultFrom,
      chainId: config.chainId
    });
  }

  /**
   * Single-call deposit + ETH→token swap. Used by the `*WithGas`
   * variants on the token classes; consumers calling this directly
   * supply the full `swapCallData` (typically generated by an off-
   * chain quoter such as 0x or 1inch).
   */
  depositWithGas(
    tokenAddress: string,
    depositAmount: string,
    userAddress: string,
    swapCallData: string,
    options: ContractCallerOptions = {}
  ): Promise<TxResult> {
    return withOperation({
      error: DepositError,
      info: { operation: 'depositWithGas', mode: 'write', tokenAddress, method: 'swapAndBridge' },
      run: () =>
        this.#caller.write(
          'swapAndBridge',
          [tokenAddress, amountOf(depositAmount), userAddress, swapCallData],
          options
        )
    });
  }

  /** Same as {@link depositWithGas} but returns the unsigned `{ to, data, value? }`. */
  prepareDepositWithGas(
    tokenAddress: string,
    depositAmount: string,
    userAddress: string,
    swapCallData: string,
    options: ContractCallerOptions = {}
  ): Promise<PreparedTx> {
    return withOperation({
      error: DepositError,
      info: {
        operation: 'prepareDepositWithGas',
        mode: 'prepare',
        tokenAddress,
        method: 'swapAndBridge'
      },
      run: () =>
        this.#caller.prepareWrite(
          'swapAndBridge',
          [tokenAddress, amountOf(depositAmount), userAddress, swapCallData],
          options
        )
    });
  }
}
